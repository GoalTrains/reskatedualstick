"""Build the trick path table for Session Controls from skate.'s own gesture data.

Recognizer space (as stored in the game's assets): x right, y DOWN, angle 0 = down, 90 = right.
For every trick we synthesize a stick path, check it against a model of the recognizer
(points patterns and arc patterns), check which other tricks it would also satisfy, and
write a C table (XInput space, y up) for the DLL.
"""
import json, math, sys

G = json.load(open(sys.argv[1]))

def ang(x, y):  # recognizer angle in degrees
    a = math.degrees(math.atan2(x, y))
    return a % 360

def in_arc(t, a, b):
    return a <= t <= b if a <= b else (t >= a or t <= b)

def match_points(path, p):
    k = 0
    for x, y in path:
        px, py = p['pts'][k]
        if math.hypot(x - px, y - py) <= p['tol']:
            k += 1
            if k == len(p['pts']):
                return True
    return False

def match_arcs(path, p):
    k = 0
    for x, y in path:
        m = math.hypot(x, y)
        a = p['arcs'][k]
        mn, mx = a.get('mn', 0.5), a.get('mx', 1.0)
        if mn <= m <= mx + 1e-6 and in_arc(ang(x, y), a['a'], a['b']):
            k += 1
            if k == len(p['arcs']):
                return True
    return False

def matches(path, g):
    for p in g['patterns']:
        if p['mode'] == 0 and p['pts'] and match_points(path, p):
            return True
        if p['mode'] == 1 and p['arcs'] and match_arcs(path, p):
            return True
    return False

def framed(core, nollie):
    pre = [(0, -0.9)] * 4 if nollie else [(0, 0.9)] * 4   # preload: pop direction
    return pre + core + [core[-1], (0, 0), (0, 0)]

def mid(a, b):
    if a <= b:
        return (a + b) / 2
    return ((a + b + 360) / 2) % 360

def sdelta(a, b):  # signed shortest a->b
    return (b - a + 180) % 360 - 180

def synth_points(p):
    pts = []
    prev = None
    for x, y in p['pts']:
        if prev is not None:
            d = math.hypot(x - prev[0], y - prev[1])
            steps = max(1, int(d // 0.35))
            for i in range(1, steps):
                pts.append((prev[0] + (x - prev[0]) * i / steps, prev[1] + (y - prev[1]) * i / steps))
        pts.append((x, y))
        prev = (x, y)
    return pts

def synth_arcs(p):
    pts = []
    if True:
        targets = []
        for a in p['arcs']:
            mn, mx = a.get('mn', 0.5), a.get('mx', 1.0)
            mag = min(0.95, mx - 0.02) if mx > mn + 0.04 else mx
            mag = max(mag, mn + 0.03)
            targets.append((mid(a['a'], a['b']), mag))
        prev = None
        for t, m in targets:
            if prev is not None and abs(sdelta(prev[0], t)) <= 100:
                d = sdelta(prev[0], t)
                steps = max(1, int(abs(d) // 20))
                for i in range(1, steps):
                    tt = prev[0] + d * i / steps
                    mm = prev[1] + (m - prev[1]) * i / steps
                    pts.append((math.sin(math.radians(tt)) * mm, math.cos(math.radians(tt)) * mm))
            pts.append((math.sin(math.radians(t)) * m, math.cos(math.radians(t)) * m))
            prev = (t, m)
    return pts

def min_mid_radius(c):
    """How close the path comes to the centre, ignoring its last point (the final flick)."""
    if len(c) < 3: return 1.0
    return min(math.hypot(x, y) for x, y in c[1:-1])

def synth(g, name):
    """v0.13: prefer sweeps around the edge of the stick (the game's arc patterns) - that is how a
    thumb draws them. v0.12 preferred whatever overlapped least in this model, which picked
    shapes cutting through the centre (laser flip read as 360 inward heelflip in game)."""
    cands = []
    for p in g['patterns']:
        if p['mode'] == 1 and p['arcs']: cands.append(('arc', synth_arcs(p)))
        if p['mode'] == 0 and p['pts']: cands.append(('pts', synth_points(p)))
    best = None
    for kind, c in cands:
        path = framed(c, g['nollie'])
        if not matches(path, g): continue
        amb = sum(1 for m in G if m != name and matches(path, G[m]))
        through_centre = min_mid_radius(c) < 0.45
        key = (through_centre, kind != 'arc', amb, len(c))
        if best is None or key < best[0]: best = (key, c)
    return best[1] if best else cands[0][1]


names = sorted(G)
table = {}
ok = True
for n in names:
    core = synth(G[n], n)
    path = framed(core, G[n]['nollie'])
    own = matches(path, G[n])
    others = [m for m in names if m != n and matches(path, G[m])]
    table[n] = core
    flag = 'OK ' if own else 'BAD'
    if not own:
        ok = False
    print('%s %-22s %d pts  also matches: %s' % (flag, n, len(core), ', '.join(others) or '-'))

# C table (XInput space: y up)
with open(sys.argv[2], 'w') as f:
    f.write('/* Generated by data/gen.py from the game\'s gesture assets. XInput space (+y up). */\n')
    f.write('typedef struct { const char* name; int anim; int nollie; int count; float xy[24][2]; } sc_trick;\n')
    f.write('static const sc_trick sc_tricks[] = {\n')
    for n in names:
        c = table[n]
        f.write('    {"%s", %d, %d, %d, {%s}},\n' % (n, G[n]['anim'] or 0, int(G[n]['nollie']), len(c),
                ', '.join('{%.3ff, %.3ff}' % (x, -y) for x, y in c)))
    f.write('};\n#define SC_TRICK_COUNT %d\n' % len(names))
json.dump({n: table[n] for n in names}, open(sys.argv[2] + '.json', 'w'))

# ---- v0.15 test mode: every shape the game defines for every trick, for in-game calibration ----
def describe(c):
    names = ['down', 'down-right', 'right', 'up-right', 'up', 'up-left', 'left', 'down-left']
    out = []
    for x, y in c:
        if math.hypot(x, y) < 0.3: w = 'centre'
        else: w = names[int(((ang(x, y) + 22.5) % 360) // 45)]
        if not out or out[-1] != w: out.append(w)
    return ' > '.join(out)

with open(sys.argv[2].replace('tricks.h', 'tricks_all.h'), 'w') as f:
    f.write('/* Generated by data/gen.py: every shape the game defines for each trick (test mode). */\n')
    f.write('typedef struct { const char* name; const char* desc; int count; float xy[24][2]; } sc_variant;\n')
    f.write('static const sc_variant sc_variants[] = {\n')
    total = 0
    for n in names:
        g = G[n]
        k = 0
        for p in g['patterns']:
            if p['mode'] == 1 and p['arcs']: c, kind = synth_arcs(p), 'sweep'
            elif p['mode'] == 0 and p['pts']: c, kind = synth_points(p), 'points'
            else: continue
            if not c or len(c) > 24: continue
            k += 1; total += 1
            d = '%s %d: %s' % (kind, k, describe(c))
            f.write('    {"%s", "%s", %d, {%s}},\n' % (n, d, len(c), ', '.join('{%.3ff, %.3ff}' % (x, -y) for x, y in c)))
    f.write('};\n#define SC_VARIANT_COUNT %d\n' % total)
print('variants written:', total)

sys.exit(0 if ok else 1)
